void renderTexture(SDL_Texture *tex, SDL_Renderer *ren, double x, double y) //Simply renders a texture to a position. 
{
	//Setup the destination rectangle to be at the position we want
	SDL_Rect dst;
	dst.x = x;
	dst.y = y;
	//Query the texture to get its width and height to use
	SDL_QueryTexture(tex, NULL, NULL, &dst.w, &dst.h);
	SDL_RenderCopy(mainren, tex, NULL, &dst);
}

void renSpec(SDL_Renderer* ren,SDL_Texture* texs, int w, int h,double x, double y) //Renders something with a specific height and width at a certain location.
{
	SDL_Rect rect;
	rect.x = x;
	rect.y = y;
	rect.w = w;
	rect.h = h;
	SDL_RenderCopy(ren,texs, NULL,&rect);	
}

